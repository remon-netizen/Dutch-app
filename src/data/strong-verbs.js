// The perfect as it is learned and typed: the hij-form with its auxiliary.
// For a verb that takes both, the first is the one shown.
const AUX = { h: ['heeft'], z: ['is'], hz: ['heeft', 'is'] };
export const perfForms = v => (v.part ? (AUX[v.aux] || []).map(a => `${a} ${v.part}`) : []);
export const pastForms = v => v.past.split(' / ');
export const auxName = v => ({ h: 'hebben', z: 'zijn', hz: 'hebben or zijn' })[v.aux] || '';
