// ── The irregular verbs ──────────────────────────────────────────────────────
// The strong and irregular verbs a learner needs up to B2, grouped by the way
// their vowel changes: a group is learned as a pattern, which is far easier than
// a list. Regular verbs are not here: their forms follow from 't kofschip.
//
// A row: [infinitive, meaning, simple past (ik/hij), simple past plural,
//         past participle, auxiliary]
//   auxiliary  h = hebben · z = zijn · hz = both: zijn when the verb is about going
//              somewhere or about a change that happened to the subject, hebben otherwise
//   "a / b" in the simple past: both forms are right (wilde / wou)
//   zullen has no participle.

const group = (id, title, pattern, note, rows) => ({
  id, title, pattern, note,
  verbs: rows.map(([inf, en, past, pastPl, part, aux]) => ({ inf, en, past, pastPl, part, aux, group: id })),
});

