#!/usr/bin/env node
// Turn the unit files into src/data/path/{a2,b1,b2}.js, in syllabus order.
//   node tools/path/assemble.mjs
// Validate first (validate.mjs); this script does not check content.

import fs from 'fs';
import path from 'path';

const here = path.dirname(new URL(import.meta.url).pathname);
const dir = path.join(here, 'units');
const outDir = path.resolve(here, '../../src/data/path');
const order = JSON.parse(fs.readFileSync(path.join(here, 'syllabus.json'), 'utf8')).units.map(u => u.id);

const units = fs.readdirSync(dir).filter(f => f.endsWith('.json')).map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
units.sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));

const KEYS = ['id', 'level', 'icon', 'title', 'grammar', 'summary', 'explain', 'words', 'sentences', 'exercises'];
const pick = u => Object.fromEntries(KEYS.filter(k => k in u).map(k => [k, u[k]]));

for (const level of ['A2', 'B1', 'B2']) {
  const mine = units.filter(u => u.level === level).map(pick);
  // One unit per line: compact to load, still line-diffable.
  const body = mine.length ? '[\n' + mine.map(u => '  ' + JSON.stringify(u)).join(',\n') + '\n]' : '[]';
  const src = `// ${level} units of the course. Shape: see ./index.js and tools/path/spec.md.\n// Generated by tools/path/assemble.mjs from tools/path/units/*.json; edit those, then re-run.\nexport const ${level} = ${body};\n`;
  fs.writeFileSync(path.join(outDir, `${level.toLowerCase()}.js`), src);
  console.log(`${level}: ${mine.length} units`);
}
